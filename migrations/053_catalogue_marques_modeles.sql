UPDATE brands SET "Name" = upper("Name") WHERE "Name" <> upper("Name");

-- 2) Marques absentes (la première orthographe du catalogue fait foi).
INSERT INTO brands ("Name", "IsActive", "CreatedAt")
SELECT DISTINCT ON (pg_temp.norm(c.marque)) c.marque, true, now()
FROM catalogue c
WHERE NOT EXISTS (SELECT 1 FROM brands b WHERE pg_temp.norm(b."Name") = pg_temp.norm(c.marque))
ORDER BY pg_temp.norm(c.marque), c.marque;

-- Modèles absents de leur marque. Une marque déjà en double en base : la plus ancienne.
INSERT INTO vehicle_models ("BrandId", "Name", "VehicleType", "IsActive", "CreatedAt")
SELECT DISTINCT ON (b."Id", pg_temp.norm(c.modele)) b."Id", c.modele, c.type, true, now()
FROM catalogue c
CROSS JOIN LATERAL (
  SELECT b."Id" FROM brands b
  WHERE pg_temp.norm(b."Name") = pg_temp.norm(c.marque)
  ORDER BY b."Id" LIMIT 1
) b
WHERE NOT EXISTS (
  SELECT 1 FROM vehicle_models m
  WHERE m."BrandId" = b."Id" AND pg_temp.norm(m."Name") = pg_temp.norm(c.modele)
)
ORDER BY b."Id", pg_temp.norm(c.modele), c.modele;

