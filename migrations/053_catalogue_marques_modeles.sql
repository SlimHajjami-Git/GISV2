--
-- Constat : les listes « Marque » et « Modèle » de la fiche véhicule ne proposaient
-- que 27 marques, dont 8 sans aucun modèle (BMW, Honda, MAN, Mazda, Mitsubishi,
-- Nissan, Suzuki, Volvo), et 128 modèles. Le client ne trouvait pas son véhicule ;
-- le tutoriel devait laisser passer Marque et Modèle vides. Karim : « ajoute dans
-- la liste déroulante de marque et modèle toutes les marques avec leurs modèles »
-- — voitures, utilitaires, camions et bus vendus en Tunisie, en Algérie et en
-- France, modèles des vingt dernières années environ.
--
-- Karim, même jour : « mettre toutes les marques en majuscule » — elles étaient
-- mélangées (« AUDI », « KIA » à côté de « Renault », « Peugeot »).
--
-- Modèle : rejouable. 1) Les noms de marques existants passent en majuscules (seule
-- modification ; vehicles.brand, le texte déjà enregistré sur chaque véhicule, n'est
-- pas touché — la fiche retrouve sa marque sans tenir compte de la casse). 2) Ajout des
-- marques et modèles absents : une marque est reconnue par son nom normalisé
-- (minuscules, sans accents, sans espaces ni ponctuation : « AUDI » = « Audi »,
-- « T.CROSS » = « T-Cross ») ; un modèle, par ce nom normalisé DANS SA marque. Rien
-- n'est supprimé : les doublons et les erreurs déjà présents en base (TN :
-- 45 couples en double, « LEON » rangé chez KIA, types « van »/« hatchback » que la
-- fiche ne connaît pas) restent à traiter à part, sur décision de Karim.
-- vehicle_models."VehicleType" reprend les valeurs de la liste « Type » de la fiche
-- (citadine, suv, utilitaire, camion, other) : choisir le modèle y positionne le type.
-- 111 marques, 1147 modèles dans le catalogue ci-dessous.
--
-- Tables : brands ("Id" identité, "Name", "LogoUrl", "IsActive", "CreatedAt") et
-- vehicle_models ("Id" identité, "BrandId" → brands ON DELETE CASCADE, "Name",
-- "VehicleType", "IsActive", "CreatedAt"). Aucune colonne mappée par EF n'est
-- ajoutée : l'ordre SQL / pod API est indifférent.

