-- 069 — Clé d'automatisation de l'API (plainte d'un client, 18/11/2026).
--
-- Constat : le client lit les arrêts de ses véhicules par une tâche planifiée (crontab). Or le
-- jeton d'API (migration 064) ne sert qu'une fois, expire au bout de 15 minutes et ne se génère
-- que dans l'interface, après ressaisie de l'e-mail et du mot de passe : quelqu'un devait donc
-- générer un jeton à la main CHAQUE JOUR pour que la tâche tourne. Une tâche planifiée ne peut pas
-- fonctionner ainsi.
--
-- Modèle : l'administrateur de la société crée UNE FOIS une clé d'automatisation (`clyk_…`) dans
-- Profil > Accès API, après ressaisie de son e-mail et de son mot de passe. La clé n'ouvre AUCUNE
-- donnée par elle-même : elle ne sert qu'à obtenir, par POST /api/api-tokens/echange, un jeton
-- à usage unique de 15 minutes, identique à ceux de la migration 064 (arrêts seulement, 31 jours,
-- droits et véhicules de l'administrateur qui a créé la clé). La tâche planifiée échange la clé puis
-- appelle l'API avec le jeton obtenu. Seule l'empreinte SHA-256 de la clé est stockée ; la clé
-- complète n'est montrée qu'une fois.
--
-- Garde-fous : clé révocable (revoked_at), expiration à 12 mois, 2 clés actives au plus par
-- société, 100 échanges par 24 heures glissantes et par clé (comptés sur api_tokens.api_key_id,
-- qui sert aussi de journal des échanges avec leur adresse IP), et à CHAQUE échange la règle de
-- 064/065 est relue (administrateur actif, société dont l'accès API est activé par Belive).
--
-- Ce qui ne change pas : les jetons générés à la main (api_key_id NULL) et tout le contrôle des
-- appels avec un jeton.
--
-- Ordre : à jouer AVANT le pod API qui mappe la table et la colonne. Rejouable sans effet.

CREATE TABLE IF NOT EXISTS api_keys (
    id                  integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id          integer      NOT NULL,
    user_id             integer      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    label               varchar(100) NOT NULL,
    key_prefix          varchar(16)  NOT NULL,
    key_hash            varchar(64)  NOT NULL,
    expires_at          timestamptz  NOT NULL,
    revoked_at          timestamptz  NULL,
    revoked_by_user_id  integer      NULL,
    last_used_at        timestamptz  NULL,
    last_used_ip        varchar(64)  NULL,
    created_ip          varchar(64)  NULL,
    created_at          timestamptz  NOT NULL DEFAULT now(),
    updated_at          timestamptz  NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS ux_api_keys_key_hash ON api_keys (key_hash);
CREATE INDEX IF NOT EXISTS ix_api_keys_company ON api_keys (company_id, created_at DESC);

-- Jeton obtenu par échange d'une clé (NULL = jeton généré à la main dans le profil).
ALTER TABLE api_tokens ADD COLUMN IF NOT EXISTS api_key_id integer NULL
    REFERENCES api_keys (id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS ix_api_tokens_api_key ON api_tokens (api_key_id, created_at DESC)
    WHERE api_key_id IS NOT NULL;
